import { existsSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const networkName = 'readyops-local-network';
const perUserDocker = join(
  process.env.LOCALAPPDATA ?? '',
  'Programs',
  'DockerDesktop',
  'resources',
  'bin',
  'docker.exe',
);
const docker =
  process.platform === 'win32' && existsSync(perUserDocker)
    ? perUserDocker
    : process.platform === 'win32'
      ? 'docker.exe'
      : 'docker';
const supabaseCli = fileURLToPath(
  new URL('../node_modules/supabase/dist/supabase.js', import.meta.url),
);

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: process.cwd(),
    stdio: 'inherit',
    ...options,
  });

  if (result.error) {
    console.error(result.error.message);
    process.exit(1);
  }

  return result.status ?? 1;
}

const networkCheck = spawnSync(docker, ['network', 'inspect', networkName], {
  cwd: process.cwd(),
  stdio: 'ignore',
});

if (networkCheck.status !== 0) {
  const createStatus = run(docker, [
    'network',
    'create',
    '-o',
    'com.docker.network.bridge.host_binding_ipv4=127.0.0.1',
    networkName,
  ]);

  if (createStatus !== 0) process.exit(createStatus);
}

const startStatus = run(process.execPath, [
  supabaseCli,
  'start',
  '--network-id',
  networkName,
]);

if (startStatus !== 0) process.exit(startStatus);

if (existsSync('.env.local')) {
  console.log('Kept the existing .env.local file unchanged.');
  process.exit(0);
}

const statusResult = spawnSync(process.execPath, [supabaseCli, 'status', '-o', 'json'], {
  cwd: process.cwd(),
  encoding: 'utf8',
});

if (statusResult.status !== 0) {
  console.warn('Supabase started, but its browser environment could not be generated.');
  process.exit(0);
}

const status = JSON.parse(statusResult.stdout);
const apiUrl = status.API_URL ?? status.api_url ?? status.api?.url;
const publicKey =
  status.PUBLISHABLE_KEY ??
  status.ANON_KEY ??
  status.publishable_key ??
  status.anon_key;

if (!apiUrl || !publicKey) {
  console.warn('Supabase started, but the public URL or key was missing from status output.');
  process.exit(0);
}

writeFileSync(
  '.env.local',
  [
    '# Local-only browser configuration generated by npm run supabase:start.',
    `VITE_SUPABASE_URL=${apiUrl}`,
    `VITE_SUPABASE_ANON_KEY=${publicKey}`,
    '',
  ].join('\n'),
  { encoding: 'utf8', flag: 'wx' },
);

console.log('Created .env.local with the local Supabase public key only.');
