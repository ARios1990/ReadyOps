import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import ts from 'typescript';
const require = createRequire(import.meta.url);
const storage = new Map();
global.window = { location: { search: '?service_needed=(Profile.Services Needed)&contract=(Profile.Contract)' }, localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) }, setInterval, clearInterval };
const calls = [], transcriptCalls = [];
let failTranscript = true, booked = 0;
const day = '2030-10-14';
const portal = { company: { company: { id: 'company', name: 'Test Roofing', slug: 'test-roofing', state: 'TX' }, settings: { timezone: 'America/Chicago', allowPublicBooking: true, formMode: 'internal', requirementsShort: '', requirementsDetail: '' }, locations: [] }, week: [{ day: 'Monday', date: day, openings: 1, booked: 0, closed: false, slots: [{ start: '18:00', end: '19:00', status: 'available', capacity: 1, bookedCount: 0 }] }] };
const supabase = {
  async rpc(name, args) {
    calls.push({ name, args });
    if (name === 'get_public_service_templates') return { data: [load('serviceTemplates').DEFAULT_SERVICE_TEMPLATES.find(item => item.id === 'roofing')] };
    if (name === 'get_public_booking_portal_active_locations') return { data: portal };
    if (name === 'get_public_location_timezone') return { data: 'America/Chicago' };
    if (name === 'reserve_public_appointment_slot') return { data: { reservation_token: 'reservation', appointment_date: day, start_time: '18:00', end_time: '19:00', undo_deadline: new Date(Date.now() + 60000).toISOString() } };
    if (name === 'submit_public_appointment') return { data: { lead_id: 'new-lead', lead_code: 'TEST-NEW', manage_token: 'management', appointment_date: day, start_time: '18:00', form_data: args.p_form_data, qc_status: 'pending' } };
    throw new Error(`Unexpected RPC ${name}`);
  },
  functions: { async invoke(name, args) { transcriptCalls.push({ name, args }); return failTranscript ? { error: new Error('Temporary failure') } : { data: { saved: true } }; } },
};
const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name);
  const file = ['tsx', 'ts'].map(extension => new URL(`../src/${name}.${extension}`, import.meta.url)).find(path => fs.existsSync(path));
  const module = { exports: {} }; cache.set(name, module.exports);
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText;
  new Function('exports', 'require', 'module', code)(module.exports, id => {
    if (id === './supabase') return { supabase };
    if (id === './brand') return { READYOPS_LOGO_DATA_URI: '' };
    if (id === './AgentWeatherPreview') return { AgentWeatherPreview: () => null, useWeeklyWeather: () => ({ daily: {}, loading: false, hasLocation: false }) };
    return id.startsWith('./') ? load(id.slice(2)) : require(id);
  }, module);
  return module.exports;
}
const { AgentBookingPortal } = load('AgentBookingPortal');
const { ROOFING_SERVICE_OPTIONS, contractValue, savedServiceValue } = load('bookingDefaults');
assert.equal(savedServiceValue('(Profile.Services Needed)'), '');
assert.equal(savedServiceValue('roof repair'), 'Roof Repair');
assert.equal(savedServiceValue('Existing custom service'), 'Existing custom service');
assert.equal(contractValue(''), 'No');
assert.equal(contractValue('(Profile.Contract)'), 'No');
assert.equal(contractValue('Yes'), 'Yes');
let renderer;
const settle = async action => act(async () => { action?.(); for (let i = 0; i < 8; i++) await Promise.resolve(); });
const draft = { values: { full_name: 'Test Customer', phone_number: '2105550123', address: '12 Oak St', city: 'Converse', state: 'TX', zip_code: '78109', service_needed: '', contract: '', recording_notes: 'The customer asked for a repair.' }, requestedDate: day, requestedTime: '18:00', timeRange: '', warnings: [], sources: {}, transcript: 'The customer asked for a repair.' };
await settle(() => { renderer = TestRenderer.create(React.createElement(AgentBookingPortal, { slug: 'test-roofing', importedDraft: draft, bookingAgentName: 'Test Agent', onBooked: () => booked++ })); });
const select = label => renderer.root.findAllByType('select').find(node => node.props['aria-label'] === label);
assert.equal(select('Service Requested').props.value, '');
assert.equal(select('Service Requested').props.required, true);
assert.equal(select('Service Requested').props.multiple, undefined);
assert.deepEqual(select('Service Requested').findAllByType('option').map(node => node.children.join('')), ['Select Service', ...ROOFING_SERVICE_OPTIONS]);
assert.equal(select('Signed with another contractor?').props.value, 'No');
assert.ok(select('Signed with another contractor?').findAllByType('option').every(node => node.props.value));
const slot = renderer.root.findAllByType('button').find(node => node.findAllByType('span').some(span => span.children.join('') === 'Available'));
await settle(() => slot.props.onClick());
await settle(() => renderer.root.findByType('form').props.onSubmit({ preventDefault() {} }));
assert.equal(calls.filter(call => call.name === 'submit_public_appointment').length, 0, 'Service Requested cannot be submitted blank');
await settle(() => select('Service Requested').props.onChange({ target: { value: 'Roof Repair' } }));
await settle(() => select('Signed with another contractor?').props.onChange({ target: { value: 'Yes' } }));
await settle(() => renderer.root.findByType('form').props.onSubmit({ preventDefault() {} }));
const submissions = () => calls.filter(call => call.name === 'submit_public_appointment');
assert.equal(submissions().length, 1);
assert.equal(submissions()[0].args.p_form_data.service_needed, 'Roof Repair');
assert.equal(submissions()[0].args.p_form_data.contract, 'Yes');
assert.equal(submissions()[0].args.p_form_data.address, '12 Oak St, Converse, TX 78109');
assert.equal(submissions()[0].args.p_agent_name, 'Test Agent');
assert.equal(booked, 1);
