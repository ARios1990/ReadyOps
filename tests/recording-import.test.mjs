import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const module = { exports: {} };
const code = ts.transpileModule(fs.readFileSync(new URL('../src/recordingImport.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
new Function('exports', 'module', code)(module.exports, module);
const { fullAddress, prepareDraft, matchCallLog, requestedAppointment, normalizePhone } = module.exports;
const row = { 'First Name': 'Test', 'Last Name': 'Customer', Phone: '(210) 555-0123', Address: '12 Oak St', City: 'Converse', State: 'TX', 'Zip Code': '78109', 'Recording Start': '2026-10-11 12:00:00', 'Call Notes': 'October 12 2026 At: 6 Pm 7-8Yrs,Insured,No Contract Sign English', 'Scheduled time': '2026-10-13 17:45:00' };
assert.equal(fullAddress(row.Address, row.City, row.State, row['Zip Code']), '12 Oak St, Converse, TX 78109');
assert.equal(fullAddress('12 Oak St, Converse, TX 78109', row.City, row.State, row['Zip Code']), '12 Oak St, Converse, TX 78109');
const draft = prepareDraft(row, 'How many stories? Do you have a claim? Mi techo tiene 15 años. No tengo seguro.');
assert.equal(draft.values.address, '12 Oak St, Converse, TX 78109');
assert.equal(draft.requestedDate, '2026-10-12');
assert.equal(draft.requestedTime, '18:00');
assert.equal(draft.values.roof_age, '7-8');
assert.equal(draft.values.claim_filed, undefined);
assert.equal(draft.values.stories, undefined);
assert.equal(draft.values.additional_properties, '');
assert.ok(draft.warnings.some(w => w.includes('Scheduled time')));
assert.ok(draft.warnings.some(w => w.includes('Roof age differs')));
assert.ok(draft.warnings.some(w => w.includes('no insurance')));
assert.ok(draft.warnings.some(w => w.includes('Spanish')));
assert.ok(draft.values.recording_notes.includes('Mi techo tiene 15 años.'));
assert.equal(matchCallLog('Test Customer (210) 555-0123.mp3', [row]).length, 1);
assert.equal(matchCallLog('Test Customer (210) 555-0123.mp3', [row, { ...row }]).length, 2);
assert.equal(matchCallLog('different (325) 555-0123.mp3', [row]).length, 0);
assert.equal(normalizePhone('+1 (210) 555-0123'), '2105550123');
assert.equal(normalizePhone('0123'), '');
assert.deepEqual(requestedAppointment('tomorrow at 6 pm', '2026-10-11'), { date: '2026-10-12', time: '18:00', range: '' });
assert.deepEqual(requestedAppointment('Tuesday at 6:30/7:00 pm', '2026-10-11'), { date: '2026-10-13', time: '', range: '18:30–19:00' });
assert.ok(prepareDraft({ ...row, Address: '' }).warnings.some(w => w.includes('Street address')));
assert.ok(prepareDraft({ ...row, 'Zip Code': '' }).warnings.some(w => w.includes('ZIP code')));
